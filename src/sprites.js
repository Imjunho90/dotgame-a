const sprite = (...rows) => {
  if (rows.length !== 16 || rows.some((r) => r.length !== 16)) throw new Error('sprite must be 16x16');
  return rows.map((r) => Array.from(r, (c) => (c === '.' ? -1 : Number(c))));
};

